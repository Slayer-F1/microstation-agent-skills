#!/usr/bin/env python3
"""Wrap agent-written Python so MicroStation runs it and leaves a result file.

Usage: python make_job.py <body.py> <job.py> <result.json>

The body runs inside MicroStation's Python. Set a variable named `result`
(anything JSON-friendly) to return data. print() output is captured too.
The result file is written even if the body fails: {"ok", "stdout", "result", "error"}.
"""
import sys
import textwrap

# Order matters: a wrong order breaks every later import until MicroStation restarts.
IMPORT_ORDER = ["MSPyBentley", "MSPyBentleyGeom", "MSPyECObjects",
                "MSPyDgnPlatform", "MSPyDgnView", "MSPyMstnPlatform"]

TEMPLATE = '''\
# generated by make_job.py - do not edit
import contextlib, io, json, os, traceback
{imports}

_out = io.StringIO()
_state = {{"ok": False, "stdout": "", "result": None, "error": None}}
try:
    with contextlib.redirect_stdout(_out):
        result = None
{body}
    _state["ok"] = True
    _state["result"] = result
except BaseException:
    _state["error"] = traceback.format_exc()
_state["stdout"] = _out.getvalue()
_path = {result_path!r}
with open(_path + ".tmp", "w", encoding="utf-8") as _f:
    json.dump(_state, _f, default=str, ensure_ascii=False)
os.replace(_path + ".tmp", _path)  # the file appears only when complete
'''


def make_job(body, result_path):
    imports = "\n".join(f"from {m} import *" for m in IMPORT_ORDER)
    return TEMPLATE.format(imports=imports,
                           body=textwrap.indent(body.rstrip() + "\n", " " * 8),
                           result_path=result_path)


def main(argv):
    if len(argv) != 4:
        print(__doc__)
        return 2
    with open(argv[1], encoding="utf-8") as f:
        job = make_job(f.read(), argv[3])
    compile(job, argv[2], "exec")  # fail here, not inside MicroStation
    with open(argv[2], "w", encoding="utf-8") as f:
        f.write(job)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
